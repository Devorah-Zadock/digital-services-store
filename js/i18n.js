const I18N_LANG_KEY = "deskkit_lang";

function applyLang(lang) {
  const dict = I18N[lang] || I18N.he;
  document.documentElement.lang = lang === "en" ? "en" : "he";
  document.documentElement.dir = lang === "en" ? "ltr" : "rtl";
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (dict[key] !== undefined) el.textContent = dict[key];
  });
  // Same idea as data-i18n, for the one attribute textContent can't
  // reach — an <input placeholder> (e.g. the catalog search box).
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    if (dict[key] !== undefined) el.placeholder = dict[key];
  });
  // Same idea again, for a button's hover tooltip (e.g. the CV Shell's
  // "Undo (Ctrl+Z)" title) — a real UI string, not just decoration, so
  // it shouldn't stay stuck in Hebrew once everything else switches.
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const key = el.dataset.i18nTitle;
    if (dict[key] !== undefined) el.title = dict[key];
  });
  const toggle = document.getElementById("lang-toggle");
  if (toggle) toggle.textContent = lang === "en" ? "עברית" : "EN";
  try { localStorage.setItem(I18N_LANG_KEY, lang); } catch (err) { /* storage unavailable */ }
  // Reveals the body hidden by index.html's own early inline script (see
  // its comment) — a no-op class removal when that script never hid it
  // (the common, default-Hebrew case) in the first place.
  document.documentElement.classList.remove("lang-pending");
  // Pages with their own JS-rendered content (catalog.js's product grid,
  // hero title/lead per ?type=, etc.) can't be reached by the plain
  // data-i18n sweep above — they listen for this and re-render themselves
  // in the new language instead.
  document.dispatchEvent(new CustomEvent("deskkit:langchange", { detail: { lang } }));
}

function currentLang() {
  try { return localStorage.getItem(I18N_LANG_KEY) || "he"; } catch (err) { return "he"; }
}

// No DOMContentLoaded wrapper needed: this script's own <script> tag
// sits near the end of <body>, after every data-i18n element in the
// document — by the time a plain, non-deferred script tag like this one
// actually executes, everything above it in the HTML is already
// parsed and in the DOM. Waiting for the full document (including
// everything BELOW this point too) to finish parsing only delayed
// applying the real language further, widening the exact flash this
// file exists to prevent.
// Auto-detects English for a first-time visitor whose browser isn't set
// to Hebrew (an out-of-Israel visitor, in practice) — requested live:
// "if someone from America, or anyone not from Israel, opens the
// site, can it open in English automatically?". Deliberately keyed off
// navigator.language/navigator.languages (the browser's own UI-language
// setting), not IP geolocation: no extra network call, no third-party
// lookup, and it's the same signal every other "auto-detect my
// language" site already uses. Only ever decides a FIRST visit with no
// stored preference yet — once applyLang runs once (here, or from the
// toggle), it always persists to localStorage (see applyLang's own
// setItem call) and wins over this on every later visit, so a real
// Hebrew-reading visitor whose browser happens to be in English, or
// vice versa, only ever gets overridden their very first time, and
// never again after they've either kept or changed it.
function dkDetectDefaultLang() {
  try {
    const browserLangs = navigator.languages || [navigator.language || ""];
    return browserLangs.some((l) => (l || "").toLowerCase().startsWith("he")) ? "he" : "en";
  } catch (err) { return "he"; }
}

(() => {
  let stored = null;
  try { stored = localStorage.getItem(I18N_LANG_KEY); } catch (err) { /* storage unavailable */ }
  applyLang(stored || dkDetectDefaultLang());
  // The toggle's own click handler now lives in js/header.js instead of
  // here — that script mounts the toggle into every page's header
  // (this file is still only loaded on the subset of pages with real
  // data-i18n translations, see this file's own top comment), and
  // having BOTH files bind a click listener to the same #lang-toggle on
  // the pages where they overlap fired applyLang() twice per click
  // (toggle, then immediately toggle back) — looked like the button
  // did nothing. header.js's handler already calls this same
  // applyLang() when it's available, so nothing is lost by removing
  // the duplicate here.
})();
